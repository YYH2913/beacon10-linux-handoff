"""Read the installed-storage ABI and generate its bounded C constants.

This only handles source/regular files. The kernel handoff transport remains
stock-linux-v1; stock-linux-v2 identifies the smaller root and larger P36.
"""
import argparse,json,subprocess
from pathlib import Path

ROOT=Path(__file__).resolve().parent
LAYOUT=json.loads((ROOT/'layout.json').read_text())
PARTS={p['number']:p for group in ('preserved','resized','relocated','volumes') for p in LAYOUT[group]}
STORAGE_ID=LAYOUT['id']
HANDOFF_ID=LAYOUT['handoff_protocol']
ROOTFS_BYTES=PARTS[30]['size']*LAYOUT['sector_bytes']
KERNEL_BYTES=PARTS[29]['size']*LAYOUT['sector_bytes']
BOOTSTRAP_BYTES=LAYOUT['bootstrap']['squashfs_image_max_bytes']


def validate():
    if (STORAGE_ID!='stock-linux-v2' or HANDOFF_ID!='stock-linux-v1' or
        LAYOUT['sector_bytes']!=512 or set(PARTS)!=set(range(1,38)) or
        ROOTFS_BYTES!=64<<20 or KERNEL_BYTES!=32<<20):
        raise ValueError('Unsupported installed storage ABI')
    cursor=LAYOUT['first_usable_lba']
    for part in sorted(PARTS.values(),key=lambda p:p['start']):
        if part['start']!=cursor or part['size']<=0:raise ValueError('Gap or overlap in storage ABI')
        cursor+=part['size']
    if cursor!=LAYOUT['last_usable_lba']+1:raise ValueError('Storage ABI does not use the complete usable media')
    if PARTS[30]['start']+PARTS[30]['size']!=PARTS[36]['start'] or PARTS[36]['start']%8 or PARTS[36]['size']%8:
        raise ValueError('Root/overlay boundary or 4KiB alignment mismatch')


def outputs():
    validate()
    constants={
        'B10_ROOTFS_START_SECTORS':PARTS[30]['start'],
        'B10_ROOTFS_PARTITION_BYTES':ROOTFS_BYTES,
        'B10_KERNEL_START_SECTORS':PARTS[29]['start'],
        'B10_KERNEL_PARTITION_BYTES':KERNEL_BYTES,
        'B10_OVERLAY_START_SECTORS':PARTS[36]['start'],
        'B10_OVERLAY_SECTORS':PARTS[36]['size'],
    }
    text='/* SPDX-License-Identifier: GPL-2.0-only */\n/* Generated by storage-layout.py from layout.json. */\n#ifndef B10_STORAGE_LAYOUT_H\n#define B10_STORAGE_LAYOUT_H\n'
    text+='#define B10_STORAGE_LAYOUT "'+STORAGE_ID+'"\n'
    text+=''.join('#define '+name+' '+str(value)+'ULL\n' for name,value in constants.items())+'#endif\n'
    table='/* SPDX-License-Identifier: GPL-2.0-only */\n/* Generated from tools/beacon10/layout.json; checked by storage-layout.py. */\n#ifndef B10_LAYOUT_GENERATED_H\n#define B10_LAYOUT_GENERATED_H\nstruct b10_part { const char *name; uint64_t start, sectors; };\nstatic const struct b10_part b10_parts[37] = {\n'
    table+=''.join('  { "'+p['name']+'", '+str(p['start'])+'ULL, '+str(p['size'])+'ULL },\n' for _,p in sorted(PARTS.items()))+'};\n#endif\n'
    return {ROOT/'handoff/storage-layout.h':text,ROOT/'handoff/layout-generated.h':table,
            ROOT.parents[1]/'examples/beacon10-storage-layout':STORAGE_ID+'\n'}


def check_root_marker(image):
    value=subprocess.check_output(['unsquashfs','-cat',str(image),'etc/beacon10-storage-layout'],stderr=subprocess.DEVNULL,timeout=30)
    if value!=(STORAGE_ID+'\n').encode():raise ValueError('SquashFS has the wrong installed storage ABI')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');a=p.parse_args()
    for path,value in outputs().items():
        if a.write:path.write_text(value)
        elif not path.exists() or path.read_text()!=value:raise SystemExit('Generated layout is stale: '+str(path))
    print('Storage ABI '+STORAGE_ID+': root 64MiB; P36 '+str(PARTS[36]['size']*512)+' bytes; handoff '+HANDOFF_ID)
